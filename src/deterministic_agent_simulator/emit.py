"""Generate a pytest regression test next to a signed replay file.

The generated module has two tests:

- ``..._reproduces_with_recorded_flags`` replays the file with the bug flags it was found with
  and asserts the same invariant fails with the same trace hash: the reproduction is exact.
- ``..._holds_on_current_build`` replays the same scenario against the current build (the flags
  in ``APP_SIM_BUG_FLAGS``, none by default) and asserts that no invariant is violated. It fails
  while the bug is present and passes once it is fixed, which is what a regression test is for.

The file contains only the seed, the invariant name and the replay file name, so it is safe to
commit; everything else is in the signed replay file.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from deterministic_agent_simulator.check.oracles import INVARIANTS

__all__ = ["emit_regression_test", "regression_test_source"]

_TEMPLATE = '''"""Regression test generated by deterministic-agent-simulator.

Seed: {seed}
Bug flags when found:{flags}
Violated invariant: {invariant}
Shrunk from {original} to {shrunk} trace events.

The replay file next to this test is HMAC-signed: set APP_REPLAY_HMAC_KEY to the key that
signed it. APP_SIM_BUG_FLAGS selects the build under test (empty: the reference build).
"""

from __future__ import annotations

from pathlib import Path

from deterministic_agent_simulator.replay import replay_file

REPRO = Path(__file__).with_name("{repro}")


def test_{name}_reproduces_with_recorded_flags() -> None:
    outcome = replay_file(REPRO, build="recorded")
    assert outcome.invariant == "{invariant}", outcome.report
    assert outcome.trace_hash == outcome.expected_trace_hash


def test_{name}_holds_on_current_build() -> None:
    outcome = replay_file(REPRO, build="current")
    assert outcome.violations == [], outcome.report
'''
_SAFE_NAME = re.compile(r"^[A-Za-z0-9_.-]{1,120}\.json$")


def regression_test_source(document: dict[str, Any], repro_name: str) -> str:
    """The source of a regression test for a (verified) replay document."""
    expected = document["expected"]
    invariant = str(expected["invariant"])
    if invariant not in INVARIANTS:
        raise ValueError(f"unknown invariant {invariant!r}")
    if not _SAFE_NAME.fullmatch(repro_name):
        raise ValueError("replay file names may use letters, digits, '_', '.', '-' only")
    seed = int(document["seed"])
    if seed < 0:
        raise ValueError("seeds must not be negative: the test name would not be an identifier")
    bugs = document["config"].get("bugs", [])
    flags = "".join(f"\n- {flag}" for flag in bugs) if bugs else " none"
    if not all(re.fullmatch(r"[a-z_]{1,40}", str(flag)) for flag in bugs):
        raise ValueError("unexpected bug flag name")
    return _TEMPLATE.format(
        seed=seed,
        flags=flags,
        invariant=invariant,
        original=int(expected["original_trace_length"]),
        shrunk=int(expected["trace_length"]),
        repro=repro_name,
        name=f"seed_{seed}_{invariant}",
    )


def emit_regression_test(repro_path: Path, document: dict[str, Any]) -> Path:
    """Write ``test_repro_<seed>_<invariant>.py`` next to ``repro_path``; returns its path."""
    source = regression_test_source(document, repro_path.name)
    seed = int(document["seed"])
    invariant = str(document["expected"]["invariant"])
    path = repro_path.with_name(f"test_repro_seed_{seed}_{invariant}.py")
    path.write_text(source, encoding="utf-8", newline="\n")
    return path
